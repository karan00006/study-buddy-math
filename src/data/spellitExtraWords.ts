function parseWordRow(row: string): SpellitWord {
  const [word, meaning, meaningUrdu, synonymList, antonymList] = row.split('|');
  return {
    id: word.toLocaleLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''),
    word,
    meaning,
    meaningUrdu,
    synonyms: synonymList.split(',').filter(Boolean),
    antonyms: antonymList === '-' ? [] : antonymList.split(',').filter(Boolean),
  };
}

export const SPELLIT_EXTRA_WORDS: SpellitWord[] = WORD_ROWS
  .split('\n')
  .filter(Boolean)
  .map(parseWordRow);
